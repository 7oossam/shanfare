const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const { fresh, start, setupEncounter } = await import('../dist/engine.mjs');
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
  const base = process.env.GAME_URL || 'http://127.0.0.1:8765/';
  const errors = [];
  fs.mkdirSync('/tmp/command-checks', {recursive:true});
  try {
    for (const [width, height] of [[320, 568], [360, 640], [390, 780], [430, 932], [844, 390], [1440, 900]]) {
      const page = await browser.newPage({ viewport: { width, height } });
      page.on('pageerror', e => errors.push(e.message));
      await page.goto(base);
      await page.locator('[data-action="start"]').click();
      await page.evaluate(() => document.fonts.ready);
      assert.equal(await page.locator('.command-app.is-combat').count(), 1);
      assert.equal(await page.locator('.command-chains [data-cell]').count(), 9);
      assert.equal(await page.locator('.command-chain').count(), 3);
      assert.equal(await page.locator('.command-chains .arena-actor').count(), 0);
      assert.equal(await page.locator('.command-arena [data-target]').count(), 2);
      assert.equal(await page.locator('.command-comparison').count(), 0);
      const initialScene = await page.locator('.command-arena').boundingBox();
      const compactChains = await page.locator('.command-chains').boundingBox();
      assert.ok(initialScene.height > compactChains.height * 2);
      if (width === 390) await page.screenshot({ path:'/tmp/command-checks/combat.png', fullPage:true });
      await page.locator('[data-action="plan"]').click();
      assert.equal(await page.locator('.command-app.is-planning').count(), 1);
      assert.equal(await page.locator('[data-action="activate"]').isDisabled(), true);
      const planningScene = await page.locator('.command-arena').boundingBox();
      assert.ok(planningScene.height < initialScene.height * .6);
      assert.ok((await page.locator('.command-chains').boundingBox()).height > compactChains.height);
      await page.locator('[data-target="scout"]').click();
      await page.locator('.hand-card-select[data-card="arrow.0"]').click();
      await page.locator('[data-cell="5"]').click();
      await page.locator('[data-axis="col"]').click();
      assert.equal(await page.locator('.command-choice[aria-pressed="true"]').count(), 1);
      assert.equal(await page.locator('.command-slot.in-path').count(), 3);
      await page.locator('.hand-face-toggle[data-card="arrow.0"]').click();
      assert.equal(await page.locator('.hand-card-select[data-card="arrow.0"]').getAttribute('data-face'), '1');
      assert.equal(await page.locator('[data-cell="5"]').getAttribute('aria-pressed'), 'true');
      await page.locator('[data-action="card-info"]').click();
      assert.equal(await page.locator('dialog[open]').count(), 1);
      await page.locator('[data-action="close"]').click();
      await page.locator('.hand-face-toggle[data-card="arrow.0"]').click();
      await page.locator('[data-axis="col"]').click();
      const layout = await page.evaluate(() => {
        const chain = document.querySelector('.command-chains').getBoundingClientRect();
        const hand = document.querySelector('.command-hand').getBoundingClientRect();
        const button = document.querySelector('.command-execute').getBoundingClientRect();
        const app = document.querySelector('.command-app').getBoundingClientRect();
        return { noOverlap: chain.bottom <= hand.top, buttonInside: button.bottom <= app.bottom, noOverflow: document.documentElement.scrollWidth <= innerWidth };
      });
      assert.deepEqual(layout, { noOverlap:true, buttonInside:true, noOverflow:true }, `${width} × ${height}`);
      if (width === 390) { await page.evaluate(() => {window.scrollTo(0,0); document.body.scrollTop=0;}); await page.screenshot({path:'/tmp/command-checks/planning.png',fullPage:true}); }
      const forecast = await page.locator('[data-target="scout"] .actor-label > b').textContent();
      const credit = await page.locator('[data-momentum-after]').textContent();
      await page.locator('[data-action="activate"]').click();
      assert.equal(await page.locator('.command-app.is-combat').count(), 1);
      assert.equal(await page.locator('[data-target="scout"] .actor-label > b').textContent(), forecast);
      assert.equal(await page.locator('[data-momentum-current]').textContent(), credit);
      const save = await page.evaluate(() => JSON.parse(localStorage.getItem('shanfara-roguelike-v8')));
      assert.equal(save.report.events.at(-1).action.target, 'scout');
      assert.equal(save.state.turn, 2);
      await page.reload();
      assert.equal(await page.locator('[data-target="scout"] .actor-label > b').textContent(), forecast);
      await page.locator('[data-action="help"]').click();
      assert.equal(await page.locator('dialog[open]').count(), 1);
      await page.locator('[data-action="close"]').click();
      await page.locator('[data-action="plan"]').click();
      await page.locator('[data-action="cancel"]').click();
      assert.equal(await page.locator('.command-app.is-combat').count(),1);
      assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('shanfara-roguelike-v8'))),save);
      console.log(`PASS ${width} × ${height}: two modes, chains, faces, targeting, forecast, execution, save, cancel, help`);
      await page.close();
    }
    const bossState = start(fresh(11));
    setupEncounter(bossState, 4);
    const page = await browser.newPage({ viewport: { width: 390, height: 780 } });
    page.on('pageerror', e => errors.push(e.message));
    await page.addInitScript(state => localStorage.setItem('shanfara-roguelike-v8', JSON.stringify({ state, report: null })), bossState);
    await page.goto(base);
    assert.equal(await page.locator('[data-target]').count(), 3);
    assert.equal(await page.locator('[data-target="warlord"]').isDisabled(), true);
    await page.locator('[data-target="shield_l"]').click();
    assert.equal(await page.locator('[data-target="shield_l"]').getAttribute('aria-pressed'), 'true');
    await page.locator('.hand-card-select').first().click();
    await page.locator('[data-cell="7"]').focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('[data-cell="7"]').getAttribute('aria-pressed'), 'true');
    await page.clock.install();
    await page.locator('[data-action="activate"]').click();
    assert.equal(await page.locator('.tactical-toast').count(), 1);
    await page.clock.fastForward(3600);
    assert.equal(await page.locator('.tactical-toast').count(), 0);
    console.log('PASS boss protection, keyboard placement, toast expiry');
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
